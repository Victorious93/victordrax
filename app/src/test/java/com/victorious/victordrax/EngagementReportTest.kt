package com.victorious.victordrax

import com.victorious.victordrax.db.Engagement
import com.victorious.victordrax.db.Finding
import com.victorious.victordrax.db.Note
import com.victorious.victordrax.db.ToolRun
import com.victorious.victordrax.report.EngagementReport
import com.victorious.victordrax.report.EngagementReportData
import org.junit.Assert.*
import org.junit.Test
import java.util.TimeZone

class EngagementReportTest {
    private val utc = TimeZone.getTimeZone("UTC")
    private val auth = Engagement(id = 1, name = "Acme Q4", client = "Acme", scope = "10.0.0.0/24\napp.acme.test",
        authorizedBy = "Jane CISO", authorizedDate = 1_700_000_000_000, authDocUri = "content://doc/1", createdAt = 1)
    private fun f(id: Long, title: String, sev: String, status: String = "OPEN") =
        Finding(id = id, engagementId = 1, title = title, severity = sev, status = status, createdAt = id * 1000)

    private fun md(e: Engagement = auth, fs: List<Finding> = emptyList(), runs: List<ToolRun> = emptyList(), notes: List<Note> = emptyList()) =
        EngagementReport.markdown(EngagementReportData(e, fs, runs, notes, generatedAt = 1_700_000_000_000), utc)

    @Test fun legalNoticeAndScopeAtTop() {
        val m = md()
        val legal = m.indexOf("Legal / authorization notice"); val scope = m.indexOf("## Scope")
        assertTrue(legal in 0 until scope)
        assertTrue(m.contains(LEGAL_NOTICE.replace("\n", " ").trim()))
        assertTrue(scope < m.indexOf("## Authorization"))
        assertTrue(scope < m.indexOf("## Findings"))
        assertTrue(m.contains("- `10.0.0.0/24`") && m.contains("- `app.acme.test`"))
    }

    @Test fun unauthorizedWarns() {
        val m = md(auth.copy(authDocUri = ""))
        assertTrue(m.contains("NO AUTHORIZATION RECORDED"))
        assertFalse(m.contains("Jane CISO"))
        assertTrue(md().contains("**Authorized by:** Jane CISO"))
    }

    @Test fun emptyScopeAndNoData() {
        val m = md(auth.copy(scope = ""))
        assertTrue(m.contains("(no scope recorded)"))
        assertTrue(m.contains("(none recorded)"))
        assertTrue(m.contains("(no findings)"))
        assertFalse(m.contains("## Notes"))
    }

    @Test fun runsListedChronologicallyWithTimestamps() {
        val runs = listOf(
            ToolRun(id = 2, engagementId = 1, label = "nikto", command = "nikto -h x | tee", source = "tool", target = "", startedAt = 1_700_000_600_000),
            ToolRun(id = 1, engagementId = 1, label = "nmap", command = "nmap -sV 10.0.0.1", source = "workflow:Recon", target = "10.0.0.1", startedAt = 1_700_000_000_000),
        )
        val m = md(runs = runs)
        assertTrue(m.indexOf("| nmap |") < m.indexOf("| nikto |"))
        assertTrue(m.contains("2023-11-14 22:13 UTC"))
        assertTrue(m.contains("workflow:Recon"))
        assertTrue(m.contains("nikto -h x \\| tee")) // pipes escaped in table
        assertTrue(m.contains("Tool/workflow runs: 2"))
    }

    @Test fun findingsGroupedBySeverityInOrder() {
        val fs = listOf(f(1, "Info leak", "Info"), f(2, "SQLi", "Critical"), f(3, "XSS", "Medium"), f(4, "RCE", "Critical", "CONFIRMED"))
        val m = md(fs = fs)
        val crit = m.indexOf("### Critical (2)"); val med = m.indexOf("### Medium (1)"); val info = m.indexOf("### Info (1)")
        assertTrue(crit in 0 until med && med < info)
        assertFalse(m.contains("### High"))
        assertTrue(m.indexOf("SQLi") in crit until med && m.indexOf("RCE") in crit until med)
        assertTrue(m.contains("| Critical | 2 |") && m.contains("| High | 0 |"))
        assertTrue(m.contains("**Status:** Confirmed"))
    }

    @Test fun findingDetailsAndNotes() {
        val fx = f(1, "Weak TLS", "Low").copy(target = "app.acme.test", tags = "tls,crypto", description = "TLS 1.0 enabled",
            evidence = "$ sslscan app\nTLSv1.0 enabled", evidencePaths = "content://e/1", remediation = "Disable TLS 1.0")
        val m = md(fs = listOf(fx), notes = listOf(Note(engagementId = 1, text = "kickoff\ncall", createdAt = 1_700_000_000_000)))
        listOf("**Target:** `app.acme.test`", "**Tags:** tls, crypto", "TLS 1.0 enabled", "```\n$ sslscan app\nTLSv1.0 enabled\n```",
            "- content://e/1", "**Remediation:** Disable TLS 1.0", "## Notes", "kickoff call").forEach { assertTrue(it, m.contains(it)) }
        assertTrue(m.trimEnd().endsWith("_Generated by VictorDrax. Authorized testing only._"))
    }

    @Test fun safeFileName() {
        assertEquals("VictorDrax-Acme_Q4_x-report.pdf", EngagementReport.fileName(auth.copy(name = "Acme Q4/x"), "pdf"))
        assertEquals("VictorDrax-engagement-report.md", EngagementReport.fileName(auth.copy(name = "///"), "md"))
    }
}
