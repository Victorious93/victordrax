package com.victorious.victordrax.report

import android.graphics.Color
import android.graphics.LinearGradient
import android.graphics.Paint
import android.graphics.Shader
import android.graphics.pdf.PdfDocument
import com.victorious.victordrax.db.Engagement
import com.victorious.victordrax.db.Finding
import java.io.OutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone

/** Pro report: findings with severity, CVSS, evidence, remediation; exec summary; branded PDF + Markdown. */
object FindingReport {
    private const val CYAN = 0xFF00E5FF.toInt()
    private const val MAGENTA = 0xFFFF2BD6.toInt()

    private fun fmt(ms: Long, tz: TimeZone) =
        if (ms <= 0) "not set" else SimpleDateFormat("yyyy-MM-dd HH:mm z", Locale.US).apply { timeZone = tz }.format(Date(ms))

    /** Count by severity, ordered Critical→Info. Pure; unit tested. */
    fun severityCounts(findings: List<Finding>): Map<Severity, Int> =
        Severity.entries.associateWith { s -> findings.count { Severity.fromLabel(it.severity) == s } }

    /** Highest severity present, or INFO when empty. Pure. */
    fun topSeverity(findings: List<Finding>): Severity =
        findings.map { Severity.fromLabel(it.severity) }.minByOrNull { it.ordinal } ?: Severity.INFO

    fun executiveSummary(e: Engagement, findings: List<Finding>): String {
        if (e.execSummary.isNotBlank()) return e.execSummary
        if (findings.isEmpty()) return "No findings were recorded for ${e.name}."
        val counts = severityCounts(findings).filterValues { it > 0 }
            .entries.joinToString(", ") { "${it.value} ${it.key.label}" }
        return "Assessment of ${e.name} (${e.client}) identified ${findings.size} finding(s): $counts. " +
            "The highest-severity issue is ${topSeverity(findings).label}."
    }

    fun markdown(e: Engagement, findings: List<Finding>, tz: TimeZone = TimeZone.getDefault()): String = buildString {
        appendLine("# VictorDrax Assessment Report: ${e.name}")
        appendLine()
        appendLine("- **Client:** ${e.client}")
        appendLine("- **Generated:** ${fmt(System.currentTimeMillis(), tz)}")
        appendLine()
        appendLine("## Authorization")
        if (e.isAuthorized) {
            appendLine("- Authorized by: ${e.authorizedBy}")
            appendLine("- Date: ${fmt(e.authorizedDate, tz)}")
            appendLine("- Document: ${e.authDocUri}")
        } else appendLine("> ⚠ NO AUTHORIZATION RECORDED.")
        appendLine()
        appendLine("## Executive summary")
        appendLine(executiveSummary(e, findings))
        appendLine()
        appendLine("## Findings")
        if (findings.isEmpty()) appendLine("(none)")
        findings.sortedBy { Severity.fromLabel(it.severity).ordinal }.forEachIndexed { i, f ->
            appendLine("### ${i + 1}. ${f.title} — ${Severity.fromLabel(f.severity).label}")
            if (f.cvssVector.isNotBlank()) {
                val score = Cvss.baseScore(f.cvssVector)
                appendLine("- **CVSS 3.1:** `${f.cvssVector}`" + (score?.let { " (base $it)" } ?: ""))
            }
            if (f.evidence.isNotBlank()) { appendLine("- **Evidence:**"); appendLine("```"); appendLine(f.evidence); appendLine("```") }
            if (f.remediation.isNotBlank()) appendLine("- **Remediation:** ${f.remediation}")
            appendLine()
        }
        appendLine("_Generated by VictorDrax. Authorized testing only._")
    }

    fun writePdf(e: Engagement, findings: List<Finding>, out: OutputStream, tz: TimeZone = TimeZone.getDefault()) {
        val doc = PdfDocument()
        val w = 595; val h = 842; val margin = 40f; val lineH = 15f
        val text = Paint().apply { textSize = 10f; isAntiAlias = true; color = Color.BLACK }
        val head = Paint().apply { textSize = 20f; isAntiAlias = true; color = Color.WHITE; isFakeBoldText = true }
        var pageNo = 1
        var page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, pageNo).create())
        fun drawHeader() {
            val p = Paint().apply {
                shader = LinearGradient(0f, 0f, w.toFloat(), 0f, CYAN, MAGENTA, Shader.TileMode.CLAMP)
            }
            page.canvas.drawRect(0f, 0f, w.toFloat(), 70f, p)
            // logo ring
            val ring = Paint().apply { style = Paint.Style.STROKE; strokeWidth = 4f; color = Color.WHITE; isAntiAlias = true }
            page.canvas.drawCircle(40f, 35f, 16f, ring)
            page.canvas.drawCircle(40f, 35f, 9f, ring)
            page.canvas.drawText("VictorDrax", 70f, 42f, head)
        }
        drawHeader()
        var y = 100f
        fun line(s: String, paint: Paint = text) {
            for (chunk in (if (s.isEmpty()) listOf("") else s.chunked(95))) {
                if (y > h - margin) { doc.finishPage(page); pageNo++; page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, pageNo).create()); drawHeader(); y = 100f }
                page.canvas.drawText(chunk, margin, y, paint); y += lineH
            }
        }
        line("Assessment Report: ${e.name}", Paint(text).apply { textSize = 14f; isFakeBoldText = true })
        line("Client: ${e.client}    Generated: ${fmt(System.currentTimeMillis(), tz)}")
        line("")
        line(if (e.isAuthorized) "Authorized by ${e.authorizedBy} on ${fmt(e.authorizedDate, tz)}" else "WARNING: NO AUTHORIZATION RECORDED")
        line("")
        line("Executive summary", Paint(text).apply { isFakeBoldText = true })
        line(executiveSummary(e, findings))
        line("")
        line("Findings", Paint(text).apply { isFakeBoldText = true })
        findings.sortedBy { Severity.fromLabel(it.severity).ordinal }.forEachIndexed { i, f ->
            line("${i + 1}. [${Severity.fromLabel(f.severity).label}] ${f.title}", Paint(text).apply { isFakeBoldText = true })
            if (f.cvssVector.isNotBlank()) line("   CVSS 3.1: ${f.cvssVector}" + (Cvss.baseScore(f.cvssVector)?.let { " (base $it)" } ?: ""))
            if (f.evidence.isNotBlank()) { line("   Evidence:"); f.evidence.lines().forEach { line("     $it") } }
            if (f.remediation.isNotBlank()) line("   Remediation: ${f.remediation}")
            line("")
        }
        doc.finishPage(page)
        doc.writeTo(out); doc.close()
    }
}
