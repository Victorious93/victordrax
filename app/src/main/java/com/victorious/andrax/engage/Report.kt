package com.victorious.andrax.engage

import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import com.victorious.andrax.db.Engagement
import com.victorious.andrax.db.Note
import java.io.OutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone

object Report {
    private fun fmt(ms: Long, tz: TimeZone): String =
        if (ms <= 0) "not set" else SimpleDateFormat("yyyy-MM-dd HH:mm z", Locale.US).apply { timeZone = tz }.format(Date(ms))

    fun markdown(e: Engagement, notes: List<Note>, tz: TimeZone = TimeZone.getDefault()): String = buildString {
        appendLine("# Engagement report: ${e.name}")
        appendLine()
        appendLine("- **Client:** ${e.client}")
        appendLine("- **Created:** ${fmt(e.createdAt, tz)}")
        appendLine()
        appendLine("## Authorization")
        if (e.isAuthorized) {
            appendLine("- **Authorized by:** ${e.authorizedBy}")
            appendLine("- **Date:** ${fmt(e.authorizedDate, tz)}")
            appendLine("- **Document:** ${e.authDocUri}")
        } else {
            appendLine("> ⚠ NO AUTHORIZATION RECORDED. Testing must not proceed without written permission.")
        }
        appendLine()
        appendLine("## Scope")
        e.scopeList().ifEmpty { listOf("(none)") }.forEach { appendLine("- `$it`") }
        appendLine()
        appendLine("## Notes")
        if (notes.isEmpty()) appendLine("(none)")
        notes.forEach { appendLine("- ${fmt(it.createdAt, tz)}: ${it.text.replace("\n", " ")}") }
        appendLine()
        appendLine("_Generated by Victorious ANDRAX. Authorized testing only._")
    }

    /** Very simple text PDF rendering of the markdown report (A4, monospace-ish wrap). */
    fun writePdf(markdown: String, out: OutputStream) {
        val doc = PdfDocument()
        val paint = Paint().apply { textSize = 10f; isAntiAlias = true }
        val w = 595; val h = 842; val margin = 40f; val lineH = 14f
        val maxChars = 90
        val lines = markdown.lines().flatMap { l -> if (l.isEmpty()) listOf("") else l.chunked(maxChars) }
        var pageNo = 1
        var page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, pageNo).create())
        var y = margin
        for (l in lines) {
            if (y > h - margin) {
                doc.finishPage(page); pageNo++
                page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, pageNo).create()); y = margin
            }
            page.canvas.drawText(l, margin, y, paint); y += lineH
        }
        doc.finishPage(page)
        doc.writeTo(out); doc.close()
    }
}
